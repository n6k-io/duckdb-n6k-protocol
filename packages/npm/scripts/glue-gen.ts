// Bundles the extension's JS glue into a committed C++ header (make glue-gen / glue-check).
import path from "node:path";

const PKG = path.resolve(import.meta.dir, "..");
const OUT = path.resolve(
  PKG,
  "../../src/n6k_client/include/n6k_glue_generated.hpp",
);
const DELIM = "n6kjs";

const ENTRIES = [
  ["N6K_MAIN_GLUE_JS", "src/glue/main-entry.ts"],
  ["N6K_PUMP_GLUE_JS", "src/glue/pump-entry.ts"],
] as const;

async function bundle(entry: string): Promise<string> {
  const out = await Bun.build({
    entrypoints: [path.join(PKG, entry)],
    target: "browser",
    format: "iife",
    minify: true,
  });
  if (!out.success) {
    throw new Error(`glue-gen: ${entry}:\n${out.logs.map(String).join("\n")}`);
  }
  const js = await out.outputs[0]!.text();
  if (js.includes(`)${DELIM}"`)) {
    throw new Error(`glue-gen: ${entry} contains the raw-string delimiter`);
  }
  return js;
}

const parts = await Promise.all(
  ENTRIES.map(async ([name, entry]) => {
    const js = await bundle(entry);
    return `// ${entry}\ninline constexpr const char *${name} = R"${DELIM}(${js})${DELIM}";\n`;
  }),
);

await Bun.write(
  OUT,
  "// GENERATED by packages/npm/scripts/glue-gen.ts (make glue-gen). Do not edit.\n" +
    "#pragma once\n\n" +
    "#ifdef WASM_LOADABLE_EXTENSIONS\n\n" +
    "namespace duckdb {\nnamespace n6k {\n\n" +
    "// clang-format off\n" +
    parts.join("\n") +
    "// clang-format on\n" +
    "\n} // namespace n6k\n} // namespace duckdb\n\n" +
    "#endif // WASM_LOADABLE_EXTENSIONS\n",
);
